"""Event handlers: application-service's steps of the choreographed TCE saga.

* ``agreement.generated`` → ``approved → agreement_pending``
* ``agreement.approved`` → ``agreement_pending → active`` (first report due in 6 months)
* ``report.submitted`` → next report due 6 months after the submission
"""

import logging
from datetime import UTC, datetime

from application_service.domain import InvalidTransitionError, Status, next_report_due
from application_service.models import Application
from application_service.service import status_changed_event, transition
from eh_db import Database
from eh_events import (
    AgreementApproved,
    AgreementGenerated,
    Event,
    EventType,
    Publisher,
    ReportSubmitted,
    typed_payload,
)

logger = logging.getLogger("application-service.events")

ROUTING_KEYS = [
    EventType.AGREEMENT_GENERATED.value,
    EventType.AGREEMENT_APPROVED.value,
    EventType.REPORT_SUBMITTED.value,
]
SYSTEM_ACTOR = {"actor_id": 0, "actor_role": "system"}


class SagaHandlers:
    """Dispatch consumed events to the matching use case."""

    def __init__(self, db: Database, publisher: Publisher) -> None:
        self.db = db
        self.publisher = publisher

    async def __call__(self, event: Event) -> None:
        """Entry point registered in :class:`eh_events.EventConsumer`."""
        payload = typed_payload(event)
        if event.event_type == EventType.AGREEMENT_GENERATED:
            await self.on_agreement_generated(payload)
        elif event.event_type == EventType.AGREEMENT_APPROVED:
            await self.on_agreement_approved(payload)
        elif event.event_type == EventType.REPORT_SUBMITTED:
            await self.on_report_submitted(payload)

    async def _advance(self, application_id: int, target: Status, mutate=None) -> None:
        async with self.db.session() as session:
            application = await session.get(Application, application_id)
            if application is None:
                logger.warning(
                    "event for unknown application", extra={"application_id": application_id}
                )
                return
            try:
                previous = transition(application, target, **SYSTEM_ACTOR)
            except InvalidTransitionError:
                # Late or repeated delivery of a step already applied: nothing to do.
                logger.info(
                    "saga step skipped",
                    extra={"application_id": application_id, "status": application.status},
                )
                return
            if mutate is not None:
                mutate(application)
            await session.commit()
            await self.publisher.publish(
                EventType.APPLICATION_STATUS_CHANGED, status_changed_event(application, previous)
            )

    async def on_agreement_generated(self, payload: AgreementGenerated) -> None:
        """TCE generated by document-service: wait for coordination approval."""

        def link(application: Application) -> None:
            if application.placement is not None:
                application.placement.agreement_id = payload.agreement_id

        await self._advance(payload.application_id, Status.AGREEMENT_PENDING, link)

    async def on_agreement_approved(self, payload: AgreementApproved) -> None:
        """Coordination approved the TCE: the internship becomes active."""

        def activate(application: Application) -> None:
            placement = application.placement
            if placement is not None:
                placement.activated_at = datetime.now(UTC)
                # The 6-month period counts from the start of the internship (art. 9, VII);
                # retroactive registrations may therefore already be due or overdue.
                placement.next_report_due = next_report_due(placement.start_date)

        await self._advance(payload.application_id, Status.ACTIVE, activate)

    async def on_report_submitted(self, payload: ReportSubmitted) -> None:
        """Activity report received: reset the 6-month report deadline."""
        async with self.db.session() as session:
            application = await session.get(Application, payload.application_id)
            if application is None or application.placement is None:
                return
            placement = application.placement
            submitted = payload.submitted_at.date()
            placement.last_report_at = submitted
            placement.next_report_due = next_report_due(submitted)
            placement.reports_count = (placement.reports_count or 0) + 1
